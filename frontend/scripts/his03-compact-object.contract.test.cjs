"use strict"
const { test } = require('node:test')
const { strict: assert } = require('node:assert')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8')
const sql = read('backend/app/Modules/History/HistorySql.php')
const recorder = read('backend/app/Modules/History/HistoryRecorder.php')
const policy = read('backend/app/Modules/History/HistoryPolicy.php')
const presenter = read('backend/app/Modules/History/HistoryEventPresenter.php')
const monitor = read('frontend/src/features/history/pages/HistoryMonitorView.vue')
const customer = read('frontend/src/features/customer/pages/CustomerDetailView.vue')
const client = read('frontend/src/features/history/historyPresentation.ts')
const service = read('frontend/src/services/history.ts')

test('HIS-03 compact writer uses tuples and actual empty JSON objects', () => {
  assert.match(policy, /'changed' => new \\stdClass\(\)/)
  assert.match(policy, /'count' => \[self::safeCount\(\$old\), self::safeCount\(\$new\)\]/)
  assert.match(recorder, /\['status'=>\[\$before,\$after\]\]/)
  assert.match(recorder, /\[\$field => new \\stdClass\(\)\]/)
  assert.match(presenter, /HISTORY_COMPACT_CHANGES_INVALID/)
  assert.doesNotMatch(client, /before_count|after_count|'before' in|changed in/)
  assert.match(service, /\[string \| number \| boolean \| null, string/)
})

test('HIS-03 monitor projects typed Customer code and name in one page SQL JOIN', () => {
  assert.match(sql, /c\.customer_code AS resource_code,c\.name AS resource_name/)
  assert.match(sql, /h\.resource_type = 'customer' AND c\.id = h\.resource_id/)
  assert.match(sql, /'count_sql'=>'SELECT COUNT\(\*\) AS total FROM ' \. \$table \. ' h'/)
  assert.doesNotMatch(sql, /SELECT \*/)
  assert.match(monitor, /history\.monitorIdentifier/)
  assert.match(monitor, /#cell-resource_code/)
})

test('HIS-03 opens exactly the canonical Customer modal with fresh persisted VIEW', () => {
  assert.match(monitor, /import CustomerDetailView from '@\/features\/customer\/pages\/CustomerDetailView\.vue'/)
  assert.match(monitor, /<CustomerDetailView v-if=/)
  assert.match(monitor, /:customer-id="selectedObject\.id"/)
  assert.match(customer, /const props = defineProps<\{ customerId\?: string \}>\(\)/)
  assert.match(customer, /props\.customerId \?\? String\(route\.params\.id/)
  assert.match(customer, /customerById\(id\.value\)/)
  assert.match(monitor, /hasBasePermission\('customer', 'view'\)/)
  assert.match(monitor, /authorization-mode="legacy-base-only"/)
  assert.match(monitor, /selectedObject\.value = null/)
  assert.doesNotMatch(monitor, /axios\.get\([^)]*customers/)
})
