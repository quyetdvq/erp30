import { readdir, readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const generatedRoot = join(dirname(fileURLToPath(import.meta.url)), '../src/api/generated');
const generatedMarker = '// This file is auto-generated by @hey-api/openapi-ts';

async function collectTypeScriptFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectTypeScriptFiles(path)));
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      files.push(path);
    }
  }

  return files;
}

const files = await collectTypeScriptFiles(generatedRoot);
const ownedFiles = [];

for (const file of files) {
  const source = await readFile(file, 'utf8');
  if (!source.startsWith(`${generatedMarker}\n`)) {
    throw new Error(`Generated API file is not tool-owned: ${file}`);
  }
  ownedFiles.push(file);
}

if (ownedFiles.length === 0) {
  throw new Error(`No generated TypeScript files found under ${generatedRoot}`);
}

console.log(`Verified ${ownedFiles.length} generated API TypeScript files are tool-owned.`);
