// Run ONLY after pnpm run openapi:generate; never hand-edit generated SDK.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import test from 'node:test'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, 'src/api/generated/types.gen.ts'), 'utf8')
const sdk = readFileSync(join(root, 'src/api/generated/sdk.gen.ts'), 'utf8')
const marker = '// This file is auto-generated by @hey-api/openapi-ts'
function bodyOfType(name) {
  const match = source.match(new RegExp(`export type ${name} = \\{([\\s\\S]*?)\\};`))
  assert.ok(match, `missing generated ${name}`)
  return match[1]
}
function ownerTypes(block) {
  const line = block.match(/contact_type:\s*([^;]+);/)
  assert.ok(line, 'generated contact_type missing')
  if (line[1].trim() === 'ContactOwnerType') return ['EMPLOYEE', 'ORGANIZATION', 'CUSTOMER', 'SUPPLIER']
  return [...line[1].matchAll(/'([A-Z]+)'/g)].map((match) => match[1])
}
test('SDK files retain authoritative code-generator marker', () => {
  assert.ok(source.startsWith(marker))
  assert.ok(sdk.startsWith(marker))
})
test('generated shared owner union has four canonical names', () => {
  assert.match(source, /export type ContactOwnerType\s*=/)
  const owner = source.match(/export type ContactOwnerType\s*=\s*([^;]+);/)
  assert.ok(owner)
  assert.deepEqual([...owner[1].matchAll(/'([A-Z]+)'/g)].map((m) => m[1]), ['EMPLOYEE', 'ORGANIZATION', 'CUSTOMER', 'SUPPLIER'])
})
for (const name of ['Contact', 'ContactCreate']) {
  test(`generated ${name} supports four owner values`, () => {
    assert.deepEqual(ownerTypes(bodyOfType(name)), ['EMPLOYEE', 'ORGANIZATION', 'CUSTOMER', 'SUPPLIER'])
  })
}
test('generated Contact includes optional typed boolean action hints', () => {
  const body = bodyOfType('Contact')
  assert.match(body, /allowed_actions\?:\s*\{/)
  assert.match(body, /edit\?: boolean/)
  assert.match(body, /setstate\?: boolean/)
})
test('generated ContactCreate does not accept state and PATCH cannot transfer owner', () => {
  assert.doesNotMatch(bodyOfType('ContactCreate'), /\bstatus\??:/)
  for (const field of ['contact_type', 'contact_ref_id', 'status']) {
    assert.doesNotMatch(bodyOfType('ContactPatch'), new RegExp(`\\b${field}\\??:`))
  }
})
test('SDK retains five Contact operation exports', () => {
  for (const name of ['listContacts', 'createContact', 'getContact', 'updateContact', 'setContactState']) {
    assert.match(sdk, new RegExp(`export const ${name}\\b`))
  }
})
