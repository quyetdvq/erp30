// Optimized Auto Numbering view: scoped reads, atomic cache and stale-response guards.
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const root = resolve(__dirname, '../..')
const read = (file) => readFileSync(resolve(root, file), 'utf8')
const view = read('src/features/workflow/pages/AutoNumberingView.vue')
const service = read('src/services/autoNumbering.ts')
const browser = read('e2e/ds5-hf10-auto-numbering-all.spec.ts')
const unit = read('src/services/__tests__/autoNumberingDataFlow.spec.ts')

test('filtering reuses complete authorized Resource snapshots and Refresh bypasses cache', () => {
  assert.match(view, /const seriesSnapshots = shallowRef<NumberingSeriesSnapshot>\(new Map\(\)\)/)
  assert.match(view, /if \(ids\.some\(\(id\) => !seriesSnapshots\.value\.has\(id\)\)\) return \[\]/)
  assert.match(view, /if \(!force && ids\.every\(\(id\) => seriesSnapshots\.value\.has\(id\)\)\)/)
  assert.match(view, /@submit\.prevent="void refreshSeries\(\)"/)
  assert.match(view, /if \(deniedReadUntilRefresh\.value\) \{[\s\S]*?await loadResources\(\)/)
  assert.match(view, /if \(normalizeApiError\(caught\)\?\.status !== 403\) return false/)
  assert.match(view, /deniedReadUntilRefresh\.value = true/)
  assert.match(view, /if \(!deniedReadUntilRefresh\.value\) void loadResources\(\)/)
  assert.match(view, /numberSeriesSnapshotForAll\(ids, result\.series\)/)
  assert.match(view, /numberSeriesSnapshotForResource\(seriesSnapshots\.value, resourceId, result\.data\)/)
  assert.match(browser, /reuses the All resource snapshot across filter changes without duplicate GETs/)
})

test('403 is handled before the PBAC readiness/generation guard can swallow it', () => {
  assert.match(view, /function handleReadDenial\(caught: unknown, requestSession: number\): boolean/)
  assert.match(view, /requestSession === auth\.getSessionGeneration\(\)/)
  assert.match(view, /\} catch \(caught: unknown\) \{\s*\/\/ PBAC revalidation[\s\S]*?if \(handleReadDenial\(caught, requestSession\)\) return\s*if \(generation !== resourceLoadGeneration \|\| !canConfigure\.value\) return/)
  assert.match(view, /\} catch \(caught: unknown\) \{\s*\/\/ Treat 403[\s\S]*?if \(handleReadDenial\(caught, requestSession\)\) return\s*if \(!canConfigure\.value \|\| generation !== seriesLoadGeneration\) return/)
  assert.match(browser, /a denied Resource refresh fails closed and clears the entire list/)
})

test('Auto Numbering leaves SearchableSelect popup behavior to Naive UI and tests real Refresh interaction', () => {
  const select = read('src/components/forms/SearchableSelect.vue')
  const unit = read('src/components/forms/__tests__/SearchableSelect.spec.ts')
  assert.doesNotMatch(view, /:blur-on-clear=/)
  assert.doesNotMatch(select, /blurOnClear|filterMenuOpen|@update:show|:show=/)
  assert.match(select, /@update:value="updateValue"/)
  assert.match(unit, /uses the placeholder for an empty resource filter and restores it after clearing/)
  assert.match(unit, /keeps popup visibility uncontrolled while clear and reselect update only the filter value/)
  assert.doesNotMatch(unit, /\$emit\('update:show', true\)/)
  assert.match(browser, /Clearing an NSelect value is not a request to close its filter menu/)
  assert.match(browser, /await page\.locator\('\.page-heading h1'\)\.click\(\)/)
  assert.doesNotMatch(browser, /\.n-base-select-option:visible'\)\)\.toHaveCount\(0\)/)
})

test('a successful mutation merges the canonical response, never reloads all Resource lists', () => {
  assert.match(view, /const saved = await saveNumberingSeries\(/)
  assert.match(view, /await reconcileMutation\(resourceId, saved\)/)
  assert.match(view, /const updated = await changeNumberingSeriesState\(/)
  assert.match(view, /await reconcileMutation\(String\(row\.resource_id\), updated\)/)
  assert.match(view, /numberSeriesSnapshotWithMutation\(seriesSnapshots\.value, resourceId, row\)/)
  assert.match(service, /if \(!cached\) return snapshot/)
  assert.match(unit, /does not equate a lone mutation result with a complete Resource list/)
})

test('last-request-wins and authorization failures purge stale Resource snapshots', () => {
  assert.match(view, /const generation = \+\+seriesLoadGeneration/)
  assert.match(view, /if \(generation !== seriesLoadGeneration \|\| !canConfigure\.value\) return/)
  assert.match(view, /if \(resourceId && !configurableResourceIds\.value\.includes\(resourceId\)\)/)
  assert.match(view, /seriesSnapshots\.value = new Map\(\)\s+error\.value = caught/)
  assert.match(view, /\+\+seriesLoadGeneration \/\/ Pending list responses must not overwrite this write/)
  assert.match(view, /if \(authGeneration !== resourceLoadGeneration \|\| !canConfigure\.value\) return/)
  assert.match(browser, /a denied Resource refresh fails closed and clears the entire list/)
  assert.match(unit, /rejects unauthorized or cross-Resource rows/)
})

test('details and validation discard late responses after closing or editing draft', () => {
  assert.match(view, /let viewLoadGeneration = 0/)
  assert.match(view, /if \(generation !== viewLoadGeneration \|\| !viewOpen\.value \|\| !canConfigure\.value\) return/)
  assert.match(view, /watch\(viewOpen, \(open\) => \{/)
  assert.match(view, /let validationGeneration = 0/)
  assert.match(view, /watch\(formDraft, \(\) => \{/)
  assert.match(view, /if \(generation !== validationGeneration \|\| !modalOpen\.value \|\| !canConfigure\.value\) return/)
  assert.match(view, /const resourceById = computed\(\(\) =>/)
  assert.match(view, /resourceById\.get\(String\(row\.resource_id\)\)/)
})
