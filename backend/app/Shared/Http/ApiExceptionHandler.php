<?php

declare(strict_types=1);

namespace App\Shared\Http;

use CodeIgniter\Debug\ExceptionHandler;
use CodeIgniter\Debug\ExceptionHandlerInterface;
use CodeIgniter\Exceptions\PageNotFoundException;
use CodeIgniter\HTTP\IncomingRequest;
use CodeIgniter\HTTP\RequestInterface;
use CodeIgniter\HTTP\ResponseInterface;
use Config\Exceptions;
use Throwable;

/** API errors cannot leak framework HTML pages or stack traces to the SPA. */
final class ApiExceptionHandler implements ExceptionHandlerInterface
{
    public function __construct(private readonly Exceptions $config)
    {
    }

    public function handle(Throwable $exception, RequestInterface $request, ResponseInterface $response, int $statusCode, int $exitCode): void
    {
        $path = '/' . ltrim($request->getUri()->getPath(), '/');
        $raw = parse_url((string) ($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH);
        $isApi = $path === '/api/v1' || str_starts_with($path, '/api/v1/')
            || (is_string($raw) && ($raw === '/api/v1' || str_starts_with($raw, '/api/v1/')));
        if (! $isApi) {
            if ($exception instanceof PageNotFoundException) {
                // Static image requests with missing files may reach CI4's 404 route.
                // CI4 4.7.5's HTML exception handler can throw another exception
                // while masking a stack trace without "args". Never turn a
                // normal missing-file 404 into an uncaught fatal error.
                $response->setStatusCode(404)
                    ->setHeader('Content-Type', 'text/plain; charset=utf-8')
                    ->setHeader('Cache-Control', 'no-store')
                    ->setBody('Not Found')
                    ->send();
                if (ENVIRONMENT !== 'testing') {
                    exit($exitCode);
                }
                return;
            }
            (new ExceptionHandler($this->config))->handle($exception, $request, $response, $statusCode, $exitCode);
            return;
        }

        $locale = RequestMetadata::locale();
        if ($request instanceof IncomingRequest) {
            $locale = $request->negotiate('language', ['vi', 'en']);
            $locale = in_array($locale, ['vi', 'en'], true) ? $locale : 'vi';
            $request->setLocale($locale);
        }
        // Keep the request ID generated by the request filter (even on exceptions).
        RequestMetadata::begin(RequestMetadata::id(), $locale);
        $error = ApiErrorMapper::map($exception, $statusCode);
        try {
            $security = service('security');
            $token = $security->getHash();
            if (is_string($token) && $token !== '') {
                $response->setHeader($security->getHeaderName(), $token);
            }
        } catch (Throwable) {
            // Database/boot errors still need safe JSON, with no token leak.
        }
        ApiResponder::error($response, $error['code'], $error['status'], $error['details'])->send();
        if (ENVIRONMENT !== 'testing') {
            exit($exitCode);
        }
    }
}
